async function loadEnquiry(id: string) {
  const db = await getDb();
  const [row] = await db.select().from(enquiries).where(eq(enquiries.id, id)).limit(1);
  return row ?? null;
}

export async function sendCustomerConfirmation(enquiryId: string): Promise<DeliveryResult | { skipped: true }> {
  const config = await getMailConfig();
  if (!config.notify.customerConfirmation) return { skipped: true };
  const enquiry = await loadEnquiry(enquiryId);
  if (!enquiry) return { skipped: true };

  const key: TemplateKey = enquiry.type === "QUOTE_REQUEST" ? "quote_received" : "contact_received";
  const template = await getTemplate(key);
  const vars = {
    name: enquiry.name,
    reference_number: enquiry.referenceNumber,
    service: enquiry.service ?? "your project",
    support_email: config.businessEmail,
    site_name: SITE.name,
  };
  const bodyHtml = fillTemplate(template.bodyHtml, vars, "html");
  const html = emailLayout({ bodyHtml, siteName: SITE.name, supportEmail: config.businessEmail, footerNote: `Reference ${enquiry.referenceNumber}` });
  const result = await sendEmail({
    to: enquiry.email,
    subject: fillTemplate(template.subject, vars, "text"),
    html,
    text: htmlToText(bodyHtml),
    template: key,
    enquiryId: enquiry.id,
    replyTo: config.businessEmail,
  });
  if (result.status === "SENT") {
    const db = await getDb();
    await logActivity(db, {
      enquiryId: enquiry.id,
      referenceNumber: enquiry.referenceNumber,
      action: "CONFIRMATION_SENT",
      description: `Confirmation email sent to ${enquiry.email}`,
      actor: "SYSTEM",
    });
  }
  return result;
}

export async function sendAdminNotification(enquiryId: string): Promise<DeliveryResult | { skipped: true }> {
  const config = await getMailConfig();
  if (!config.notify.newEnquiry) return { skipped: true };
  const enquiry = await loadEnquiry(enquiryId);
  if (!enquiry) return { skipped: true };

  const isQuote = enquiry.type === "QUOTE_REQUEST";
  const db = await getDb();
  const [{ files }] = await db.select({ files: sql<number>`count(*)::int` }).from(attachments).where(eq(attachments.enquiryId, enquiry.id));

  const rows: [string, string | null | undefined][] = [
    ["Reference", enquiry.referenceNumber],
    ["Type", isQuote ? "Quote request" : "Contact message"],
    ["Name", enquiry.name],
    ["Company", enquiry.company],
    ["Email", enquiry.email],
    ["Phone", enquiry.phone],
    ["Service", enquiry.service],
    ["Project type", enquiry.projectType],
    ["Timeline", enquiry.timeline],
    ["Budget", enquiry.budget],
    ["Location", [enquiry.city, enquiry.country].filter(Boolean).join(", ")],
    ["Source", enquiry.source.replace("_", " ").toLowerCase()],
    ["Landing page", enquiry.landingPage],
    ["Campaign", [enquiry.utmSource, enquiry.utmMedium, enquiry.utmCampaign].filter(Boolean).join(" / ")],
    ["Attachments", files ? `${files} file${files === 1 ? "" : "s"}` : ""],
  ];
  const table = rows
    .filter(([, value]) => value)
    .map(([label, value]) => `<tr><td style="padding:6px 12px 6px 0;color:#6b7280;vertical-align:top;white-space:nowrap;">${escapeHtml(label)}</td><td style="padding:6px 0;">${escapeHtml(String(value))}</td></tr>`)
    .join("");
  const bodyHtml =
    `<table role="presentation" cellspacing="0" cellpadding="0" style="font-size:14px;">${table}</table>` +
    `<p style="margin:20px 0 6px;color:#6b7280;font-size:13px;">${isQuote ? "Project description" : "Message"}</p>` +
    `<div style="border-left:3px solid #c16a2f;padding:4px 0 4px 12px;white-space:pre-wrap;">${escapeHtml(enquiry.projectDescription)}</div>`;
  const html = emailLayout({
    heading: isQuote ? "New quote request" : "New contact message",
    bodyHtml,
    button: { label: "View Enquiry", url: `${SITE.url.replace(/\/$/, "")}/admin/enquiries/${enquiry.id}/` },
    siteName: SITE.name,
    supportEmail: config.businessEmail,
  });
  const text =
    `${isQuote ? "New quote request" : "New contact message"} ${enquiry.referenceNumber}\n\n` +
    rows.filter(([, v]) => v).map(([l, v]) => `${l}: ${v}`).join("\n") +
    `\n\n${enquiry.projectDescription}\n\nView: ${SITE.url.replace(/\/$/, "")}/admin/enquiries/${enquiry.id}/`;

  return sendEmail({
    to: config.businessEmail,
    subject: `${isQuote ? "New Enquiry" : "New Contact Message"} — ${enquiry.referenceNumber}`,
    html,
    text,
    template: isQuote ? "admin_new_enquiry" : "admin_new_contact",
    enquiryId: enquiry.id,
    replyTo: enquiry.email,
  });
}

export async function sendPasswordReset(admin: { email: string; name: string }, link: string): Promise<DeliveryResult> {
  const config = await getMailConfig();
  const template = await getTemplate("password_reset");
  const vars = { name: admin.name, site_name: SITE.name, reset_link: link };
  const bodyHtml = fillTemplate(template.bodyHtml, vars, "html");
  const html = emailLayout({
    bodyHtml,
    button: { label: "Choose a new password", url: link },
    siteName: SITE.name,
    supportEmail: config.businessEmail,
    footerNote: "This link expires in 60 minutes.",
  });
  return sendEmail({
    to: admin.email,
    subject: fillTemplate(template.subject, vars, "text"),
    html,
    text: `${htmlToText(bodyHtml)}\n\n${link}`,
    template: "password_reset",
    storePayload: false,
  });
}

