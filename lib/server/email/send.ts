/** Templates generated by the system; these carry an Auto-Submitted header so autoresponders don't loop. */
const AUTOMATIC_TEMPLATES = new Set(["quote_received", "contact_received", "admin_new_enquiry", "admin_new_contact", "password_reset", "smtp_test"]);

export type QueueEmailInput = {
  to: string;
  cc?: string | null;
  bcc?: string | null;
  subject: string;
  html: string;
  text: string;
  template?: string;
  enquiryId?: string | null;
  messageRowId?: string | null;
  replyTo?: string;
  inReplyTo?: string;
  references?: string;
  attachmentIds?: string[];
  statusAfter?: string;
  messageId?: string;
  /** Set false for emails that must never be stored/replayed (password reset links). */
  storePayload?: boolean;
};

export type DeliveryResult = { status: EmailStatus; error?: string; logId: string };

export function makeMessageId(config: MailConfig): string {
  const domain = config.fromEmail.split("@")[1] ?? "localhost";
  return `<${randomUUID()}@${domain}>`;
}

export async function queueEmail(db: DbOrTx, input: QueueEmailInput, config: MailConfig): Promise<{ id: string; messageId: string }> {
  const messageId = input.messageId ?? makeMessageId(config);
  const payload: EmailPayload | null =
    input.storePayload === false
      ? null
      : {
          html: input.html,
          text: input.text,
          replyTo: input.replyTo,
          inReplyTo: input.inReplyTo,
          references: input.references,
          attachmentIds: input.attachmentIds,
          statusAfter: input.statusAfter,
        };
  const [row] = await db
    .insert(emailLogs)
    .values({
      enquiryId: input.enquiryId ?? null,
      messageRowId: input.messageRowId ?? null,
      recipient: singleLine(input.to).slice(0, 500),
      cc: input.cc ? singleLine(input.cc).slice(0, 500) : null,
      bcc: input.bcc ? singleLine(input.bcc).slice(0, 500) : null,
      sender: config.fromEmail,
      subject: singleLine(input.subject).slice(0, 300),
      template: input.template ?? null,
      messageId,
      status: "QUEUED",
      payload,
    })
    .returning({ id: emailLogs.id });
  return { id: row.id, messageId };
}

/**
 * Sends one queued email. Atomically claims the row first so a double click
 * on "Retry" can never send the same message twice.
 */
export async function deliverEmail(logId: string, transient?: EmailPayload): Promise<DeliveryResult> {
  const db = await getDb();
  const config = await getMailConfig();
  const staleBefore = new Date(Date.now() - 5 * 60_000);

  const [claimed] = await db
    .update(emailLogs)
    .set({ status: "SENDING", attemptCount: sql`${emailLogs.attemptCount} + 1`, lastAttemptAt: new Date() })
    .where(
      and(
        eq(emailLogs.id, logId),
        or(inArray(emailLogs.status, ["QUEUED", "FAILED"]), and(eq(emailLogs.status, "SENDING"), lt(emailLogs.lastAttemptAt, staleBefore))),
      ),
    )
    .returning();

  if (!claimed) {
    const [current] = await db.select({ status: emailLogs.status }).from(emailLogs).where(eq(emailLogs.id, logId)).limit(1);
    return { status: current?.status ?? "FAILED", logId, error: current ? undefined : "Email log not found." };
  }

  const fail = async (message: string): Promise<DeliveryResult> => {
    await db.update(emailLogs).set({ status: "FAILED", errorMessage: message }).where(eq(emailLogs.id, logId));
    if (claimed.messageRowId) await db.update(messages).set({ status: "FAILED" }).where(eq(messages.id, claimed.messageRowId));
    log.error("email.send_failed", { logId, template: claimed.template, attempt: claimed.attemptCount, error: message });
    if (claimed.enquiryId && claimed.template !== "smtp_test") {
      const [enquiry] = await db.select({ ref: enquiries.referenceNumber }).from(enquiries).where(eq(enquiries.id, claimed.enquiryId)).limit(1);
      await logActivity(db, {
        enquiryId: claimed.enquiryId,
        referenceNumber: enquiry?.ref,
        action: claimed.attemptCount > 1 ? "EMAIL_RETRIED" : "EMAIL_FAILED",
        description: `${claimed.attemptCount > 1 ? "Email retry failed" : "Email failed"}: “${claimed.subject}” to ${claimed.recipient} — ${message}`,
        actor: "SYSTEM",
        metadata: { logId },
      });
      if (config.notify.emailFailure) {
        await createNotification(db, {
          type: "EMAIL_FAILED",
          title: `Email failed for ${enquiry?.ref ?? "enquiry"}`,
          body: `“${claimed.subject}” to ${claimed.recipient}`,
          enquiryId: claimed.enquiryId,
          referenceNumber: enquiry?.ref,
          dedupeKey: `emailfail:${logId}:${claimed.attemptCount}`,
        });
      }
    }
    return { status: "FAILED", error: message, logId };
  };

  const payload = claimed.payload ?? transient;
  if (!payload) return fail("This email can no longer be sent because its content was intentionally not stored.");
  if (!config.smtp.configured) return fail("SMTP is not configured. Add your mail server details in Settings → SMTP.");

  try {
    const stored = await attachmentsByIds(payload.attachmentIds ?? []);
    const files = [];
    for (const meta of stored) {
      const found = await getAttachmentWithData(meta.id);
      if (found) files.push({ filename: meta.originalFilename, content: found.data, contentType: meta.mimeType });
    }

    const info = await sendRaw(config, {
      from: formatAddress(config.fromName, config.fromEmail),
      to: claimed.recipient,
      cc: claimed.cc ?? undefined,
      bcc: claimed.bcc ?? undefined,
      replyTo: payload.replyTo ?? config.businessEmail,
      subject: claimed.subject,
      html: payload.html,
      text: payload.text,
      messageId: claimed.messageId ?? undefined,
      inReplyTo: payload.inReplyTo,
      references: payload.references,
      attachments: files,
      headers: claimed.template && AUTOMATIC_TEMPLATES.has(claimed.template) ? { "Auto-Submitted": "auto-generated" } : undefined,
    });

    const now = new Date();
    await db
      .update(emailLogs)
      .set({ status: "SENT", sentAt: now, providerResponse: String(info.response ?? "").slice(0, 300), errorMessage: null })
      .where(eq(emailLogs.id, logId));
    if (claimed.messageRowId) {
      await db.update(messages).set({ status: "SENT", sentAt: now }).where(eq(messages.id, claimed.messageRowId));
      const [sent] = await db.select({ direction: messages.direction }).from(messages).where(eq(messages.id, claimed.messageRowId)).limit(1);
      if (sent?.direction === "OUTBOUND" && claimed.enquiryId) await applyOutboundSent(claimed.enquiryId, claimed.recipient, payload.statusAfter);
    }
    if (claimed.attemptCount > 1 && claimed.enquiryId) {
      await logActivity(db, {
        enquiryId: claimed.enquiryId,
        action: "EMAIL_RETRIED",
        description: `Email retry succeeded: “${claimed.subject}” to ${claimed.recipient}`,
        actor: "SYSTEM",
        metadata: { logId },
      });
    }
    log.info("email.sent", { logId, template: claimed.template, attempt: claimed.attemptCount });
    return { status: "SENT", logId };
  } catch (error) {
    return fail(safeError(error, config));
  }
}

export async function sendEmail(input: QueueEmailInput): Promise<DeliveryResult> {
  const db = await getDb();
  const config = await getMailConfig();
  const { id } = await queueEmail(db, input, config);
  return deliverEmail(id, input.storePayload === false ? { html: input.html, text: input.text, replyTo: input.replyTo } : undefined);
}

export async function retryEmail(logId: string): Promise<DeliveryResult> {
  return deliverEmail(logId);
}

