async function findEnquiryFor(mail: InboundEmail) {
  const db = await getDb();
  const ids = [...new Set([...(mail.inReplyTo ? [mail.inReplyTo] : []), ...mail.references])].slice(-25);

  if (ids.length) {
    // Message-IDs are unguessable (UUIDs), so a header match is trusted regardless of the sender address.
    const viaMessages = await db
      .select({ enquiryId: messages.enquiryId })
      .from(messages)
      .where(inArray(messages.messageId, ids))
      .limit(1);
    if (viaMessages[0]) return viaMessages[0].enquiryId;
    // Confirmation / notification emails are logged but not stored as messages.
    const viaLogs = await db
      .select({ enquiryId: emailLogs.enquiryId })
      .from(emailLogs)
      .where(and(inArray(emailLogs.messageId, ids), isNotNull(emailLogs.enquiryId)))
      .limit(1);
    if (viaLogs[0]?.enquiryId) return viaLogs[0].enquiryId;
  }

  // Fallback: reference number in the subject. Guessable, so the sender must be the enquiry's own customer.
  const reference = REFERENCE_PATTERN.exec(mail.subject)?.[0]?.toUpperCase();
  if (reference) {
    const [row] = await db
      .select({ id: enquiries.id })
      .from(enquiries)
      .where(and(eq(enquiries.referenceNumber, reference), eq(enquiries.email, normalizeEmail(mail.fromEmail))))
      .limit(1);
    if (row) return row.id;
  }
  return null;
}

async function validateInboundFiles(mail: InboundEmail): Promise<{ files: ValidatedFile[]; rejected: string[] }> {
  const files: ValidatedFile[] = [];
  const rejected: string[] = [];
  let total = 0;
  for (const item of mail.attachments.slice(0, MAX_ATTACHMENTS)) {
    total += item.content.length;
    if (total > MAX_TOTAL_ATTACHMENT_BYTES) {
      rejected.push(`${item.filename}: total attachment size limit reached`);
      continue;
    }
    const result = validateUpload({ name: item.filename || "attachment", data: item.content, declaredType: item.contentType }, { maxBytes: env.maxInternalFileBytes });
    if (result.ok) files.push(result.file);
    else rejected.push(`${item.filename || "attachment"}: ${result.reason}`);
  }
  for (const extra of mail.attachments.slice(MAX_ATTACHMENTS)) rejected.push(`${extra.filename}: too many attachments`);
  return { files, rejected };
}

