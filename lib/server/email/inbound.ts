export type InboundAttachment = { filename: string; contentType: string; content: Buffer };

export type InboundEmail = {
  messageId: string | null;
  inReplyTo: string | null;
  /** Message-IDs from the References header, oldest first. */
  references: string[];
  fromEmail: string;
  fromName: string;
  to: string[];
  cc: string[];
  subject: string;
  text: string;
  html: string | null;
  date: Date | null;
  attachments: InboundAttachment[];
  /** Lower-cased header name → value; only the ones used for auto-reply detection are needed. */
  headers: Record<string, string>;
};

export type IngestResult =
  | { outcome: "matched"; enquiryId: string; referenceNumber: string; messageRowId: string; attachmentsSaved: number }
  | { outcome: "created"; enquiryId: string; referenceNumber: string; messageRowId: string | null; attachmentsSaved: number }
  | { outcome: "duplicate" }
  | { outcome: "ignored"; reason: string };

const MAX_TEXT_CHARS = 100_000;
const MAX_ATTACHMENTS = 10;
const MAX_TOTAL_ATTACHMENT_BYTES = 40 * 1024 * 1024;
const NEW_ENQUIRIES_PER_HOUR = 100;

/** Statuses a customer reply re-opens. Everything else keeps its status and is only flagged unread. */
const REOPEN_TO_IN_REVIEW: readonly EnquiryStatus[] = ["AWAITING_CUSTOMER", "CLOSED", "LOST"];

// ---------------------------------------------------------------------------
// Detection helpers
// ---------------------------------------------------------------------------

export function extractMessageIds(value: string | null | undefined): string[] {
  if (!value) return [];
  return Array.from(value.matchAll(/<[^<>\s]+>/g), (m) => m[0]);
}

/** Auto-replies, bounces, mailing lists — never create or extend enquiries from these. */
export function autoGeneratedReason(mail: Pick<InboundEmail, "headers" | "fromEmail" | "subject">): string | null {
  const h = mail.headers;
  const autoSubmitted = h["auto-submitted"]?.toLowerCase().trim();
  if (autoSubmitted && autoSubmitted !== "no") return "auto-submitted";
  if (/^(bulk|junk|list|auto_reply)$/i.test(h["precedence"]?.trim() ?? "")) return "precedence";
  if (h["x-autoreply"] || h["x-autorespond"] || h["x-auto-response-suppress"]) return "auto-reply header";
  if (h["list-id"] || h["list-unsubscribe"]) return "mailing list";
  if (/^(mailer-daemon|postmaster)@/i.test(mail.fromEmail)) return "bounce";
  if (/^(auto(matic)? ?reply|out of office|undeliverable|delivery status notification|mail delivery)/i.test(mail.subject.trim())) return "auto-reply subject";
  return null;
}

/** Removes the quoted history so only what the customer just wrote is stored as the reply. */
export function stripQuotedText(text: string): string {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const cut = lines.findIndex((line, index) => {
    const trimmed = line.trim();
    if (/^on .{5,200}wrote:?$/i.test(trimmed)) return true;
    if (/^-{2,}\s*(original message|forwarded message)\s*-{2,}$/i.test(trimmed)) return true;
    if (/^_{5,}$/.test(trimmed) && /^(from|sent):/i.test(lines[index + 1]?.trim() ?? "")) return true;
    if (/^from:\s.+/i.test(trimmed) && /^(sent|date):\s/i.test(lines[index + 1]?.trim() ?? "") && index > 0) return true;
    return false;
  });
  const kept = (cut === -1 ? lines : lines.slice(0, cut)).filter((line, index, all) => !(line.startsWith(">") && all.slice(index).every((rest) => rest.startsWith(">") || rest.trim() === "")));
  const result = kept.join("\n").trim();
  return result || text.trim();
}

